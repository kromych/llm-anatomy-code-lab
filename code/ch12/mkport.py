"""Print the rows of the table of the porting experiment, from the
summaries that analyze.py wrote, and write the figure of the experiment.

Usage: python3 mkport.py [OUT.tex] [RUN_SMALL RUN_LARGE]

OUT.tex is figures/ch12-port.tex of the book's sources; without it the
figure is not written. The runs default to run2-1.7b and run2-8b.
"""
import json, pathlib, sys

here = pathlib.Path(__file__).parent
args = sys.argv[1:]
out_path = args.pop(0) if args and args[0].endswith(".tex") else None
small, large = args[:2] if len(args) > 1 else ("run2-1.7b", "run2-8b")
NAMES = {"baseline": "hand-written", "smolagents": "smolagents",
         "pydanticai": "PydanticAI", "openai_agents": "Agents SDK",
         "dspy": "DSPy"}
MODELS = ((small, "Qwen3 1.7B, Q4\\_K\\_M"), (large, "Qwen3 8B, Q8\\_0"))
runs = {d: {r["port"]: r for r in json.load(open(here / d / "summary.json"))}
        for d, _ in MODELS}
ports = [p for p in NAMES if all(p in runs[d] for d, _ in MODELS)]

def num(n):
    return f"\\num{{{n}}}" if n >= 1000 else str(n)

print("% rows of tab:ch12-port, from", small, "and", large)
for d, title in MODELS:
    if d != small:
        print("    \\addlinespace")
    print(f"    \\multicolumn{{9}}{{@{{}}l}}{{\\itshape {title}}} \\\\")
    for p in NAMES:
        if p in runs[d]:
            r = runs[d][p]
            print(f"    \\quad {NAMES[p]} & {r['loc']} & {r['correct']} & "
                  f"{r['requests_per_task']:.1f} & "
                  f"{num(r['prompt_tokens_per_task'])} & "
                  f"{num(r['completion_tokens_per_task'])} & "
                  f"{r['secs_per_task']:.1f} & {r['secs_median']:.1f} & "
                  f"{r['capped']} \\\\")

def coords(d, key):
    return " ".join(f"({runs[d][p][key]},{{{NAMES[p]}}})" for p in ports)

top = max(runs[d][p]["prompt_tokens_per_task"] for d, _ in MODELS
          for p in ports)
xmax = (int(top * 1.2) // 2000 + 1) * 2000   # room for the value labels
height = 1.3 * len(ports)
AXIS = ("xbar, bar width=5pt, y dir=reverse, symbolic y coords={%s}, "
        "ytick=data, enlarge y limits=%s, height=%.1fcm, scale only axis, "
        "xmin=0, label style={font=\\sffamily\\scriptsize, text=ink2}, "
        "tick label style={font=\\sffamily\\scriptsize, text=ink2}, "
        "axis line style={inkaxis}, major tick style={inkaxis}, "
        "xmajorgrids, major grid style={inkgrid, line width=0.3pt}, "
        "y axis line style={draw=none}, ytick style={draw=none}, "
        "nodes near coords, every node near coord/.append style="
        "{font=\\sffamily\\tiny, text=ink2, fill=white, inner xsep=1.5pt, "
        "inner ysep=0.5pt, xshift=1.5pt},"
        % (",".join(NAMES[p] for p in ports), 0.8 / len(ports), height))
out = f"""% Figure: the porting experiment of Chapter 12.  Prompt tokens per task and
% correct answers (out of 6 tasks x 3 repetitions) for each port, with
% Qwen3 1.7B (Q4_K_M) and Qwen3 8B (Q8_0) on llama-server build 12359.
% Generated by code/ch12/mkport.py from {small}/summary.json and
% {large}/summary.json, which analyze.py writes from the proxy logs.
% Standalone: `make figures` -> build/figures/ch12-port.pdf
\\begin{{tikzpicture}}
  \\def\\chtwelvesep{{{{,}}}}% a comma without the space of math punctuation
  \\begin{{axis}}[name=tok, {AXIS} width=6.0cm,
      xmax={xmax}, xlabel={{prompt tokens per task}},
      scaled x ticks=false, xticklabel style={{/pgf/number format/1000 sep=\\chtwelvesep}},
      every node near coord/.append style={{/pgf/number format/1000 sep=\\chtwelvesep}},
      legend style={{draw=none, fill=none, font=\\sffamily\\scriptsize, text=ink,
                    at={{(1.0,1.03)}}, anchor=south, legend columns=2,
                    /tikz/every even column/.append style={{column sep=10pt}}}},
      legend cell align=left, reverse legend,
      legend image code/.code={{\\fill[#1] (0cm,-0.08cm) rectangle (0.28cm,0.1cm);}}]
    \\addplot[draw=none, fill=series2] coordinates {{{coords(large, "prompt_tokens_per_task")}}};
    \\addlegendentry{{{MODELS[1][1]}}}
    \\addplot[draw=none, fill=series1] coordinates {{{coords(small, "prompt_tokens_per_task")}}};
    \\addlegendentry{{{MODELS[0][1]}}}
  \\end{{axis}}
  \\begin{{axis}}[at={{($(tok.east)+(0.9cm,0)$)}}, anchor=west, {AXIS}
      width=4.2cm, xmax=21, xtick={{0,6,12,18}}, yticklabels={{}},
      xlabel={{correct answers out of 18}}]
    \\addplot[draw=none, fill=series2] coordinates {{{coords(large, "correct")}}};
    \\addplot[draw=none, fill=series1] coordinates {{{coords(small, "correct")}}};
  \\end{{axis}}
\\end{{tikzpicture}}
"""
if out_path:
    pathlib.Path(out_path).write_text(out)
    print("wrote", out_path, "xmax", xmax)
