# genfigs.py -- write figures/ch09-stream.tex and figures/ch09-mask.tex from
# the captured data (capture.json, mask.json).
# Usage: python3 genfigs.py DATADIR FIGDIR   (for the book:
#        python3 code/ch09/scripts/genfigs.py code/ch09/results figures)
import json, sys
work, figdir = sys.argv[1], sys.argv[2]
cap = json.load(open(f"{work}/capture.json"))
mask = json.load(open(f"{work}/mask.json"))

def tex(s):
    out = []
    for ch in s:
        if ch == " ":
            out.append(r"{\color{muted}\textperiodcentered}")
        elif ch == "\n":
            out.append(r"{\color{muted}\textbackslash n}")
        elif ch in "{}_#%&$":
            out.append("\\" + ch)
        elif ch == "\\":
            out.append(r"\textbackslash{}")
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        elif ch == '"':
            out.append(r"\textquotedbl{}")
        else:
            out.append(ch)
    return "".join(out)

# ------------------------------------------------------------- stream figure
rows = []
for t, kind, payload in cap["timeline"]:
    if kind == "tool":
        d = json.loads(payload)
        if d["name"]:
            text = (r"index 0, id, name \texttt{%s}, args \texttt{%s}"
                    % (tex(d["name"]), tex(d["arguments"] or "")))
        else:
            text = r"index 0, args \texttt{%s}" % tex(d["arguments"])
        label = "tool call"
    elif kind == "content":
        text, label = r"\texttt{%s}" % tex(payload), "content"
    elif kind == "role":
        text, label = r"role \texttt{assistant}", "role"
    elif kind == "finish":
        text, label = r"finish\_reason \texttt{%s}" % tex(payload), "finish"
    elif kind == "usage":
        u = json.loads(payload)
        n_prompt = u["prompt_tokens"]
        text = r"choices \texttt{[]}, usage: %d + %d tokens" % (
            u["prompt_tokens"], u["completion_tokens"])
        label = "usage"
    else:
        text, label = r"\texttt{[DONE]}", "end"
    rows.append((t, label, text))

H = 0.33          # row height
X0, X1, TMAX = 8.0, 14.2, 460.0
def xt(t): return X0 + (X1 - X0) * t / TMAX
n = len(rows)
L = []
L.append("% Figure: one streamed Chat Completions response with a tool call,")
L.append("% as llama-server 1.0.0 (build 12359) sent it for Qwen3-1.7B Q4_K_M;")
L.append("% times measured by the client.  Generated by genfigs.py from")
L.append("% capture.json.  Standalone: `make figures`.")
L.append(r"\begin{tikzpicture}[x=1cm, y=1cm,")
L.append(r"    lbl/.style={text height=3.6pt, text depth=1.2pt}]")
top, bot = 0.35, -n * H + H / 2 - 0.1
# shaded intervals: prefill and withheld markup
t_first = rows[0][0]
t_c_end = max(t for t, k, _ in rows if k == "content")
t_tool = min(t for t, k, _ in rows if k == "tool call")
L.append(r"  \fill[cEngine!10!white] (%.3f,%.2f) rectangle (%.3f,%.2f);"
         % (xt(0), top, xt(t_first), bot))
L.append(r"  \fill[cSeam!14!white] (%.3f,%.2f) rectangle (%.3f,%.2f);"
         % (xt(t_c_end), top, xt(t_tool), bot))
for ms in range(0, 401, 100):
    L.append(r"  \draw[inkgrid, line width=0.3pt] (%.3f,%.2f) -- (%.3f,%.2f);"
             % (xt(ms), top, xt(ms), bot))
    L.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south] at "
             r"(%.3f,%.2f) {%d};" % (xt(ms), top, ms))
L.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south west] at "
         r"(%.3f,%.2f) {ms};" % (xt(440), top))
L.append(r"  \node[font=\sffamily\bfseries\scriptsize, text=ink, anchor=south west]"
         r" at (0,%.2f) {Event};" % (top + 0.02))
L.append(r"  \node[font=\sffamily\bfseries\scriptsize, text=ink, anchor=south east]"
         r" at (%.3f,%.2f) {arrival};" % (X0 - 0.15, top + 0.02))
for i, (t, label, text) in enumerate(rows):
    y = -i * H
    shape = {"content": "circle", "tool call": "rectangle"}.get(label, "circle")
    fill = {"content": "ink2", "tool call": "ink"}.get(label, "white")
    L.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=west, lbl] at (0,%.2f) {%s};"
             % (y, label))
    L.append(r"  \node[font=\sffamily\tiny, text=ink, anchor=west, lbl] at (1.05,%.2f) {%s};"
             % (y, text))
    L.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=east, lbl] at (%.3f,%.2f) {%.0f};"
             % (X0 - 0.15, y, t))
    L.append(r"  \node[%s, draw=ink, fill=%s, line width=0.4pt, inner sep=0pt,"
             r" minimum size=1.5mm] at (%.3f,%.2f) {};" % (shape, fill, xt(t), y))
# the two notes carry the fill of their interval, which hides the grid line
# behind the words
L.append(r"  \node[font=\sffamily\tiny, text=ink2, align=center, anchor=north,"
         r" fill=cEngine!10!white, inner sep=1pt] at (%.3f,%.2f)"
         r" {prefill\\%d prompt\\tokens};"
         % ((xt(0) + xt(t_first)) / 2, -0.15, n_prompt))
L.append(r"  \node[font=\sffamily\tiny, text=ink2, align=center, anchor=north,"
         r" fill=cSeam!14!white, inner sep=1pt] at (%.3f,%.2f)"
         r" {markup\\held back};" % ((xt(t_c_end) + xt(t_tool)) / 2, -3.35))
L.append(r"\end{tikzpicture}")
open(f"{figdir}/ch09-stream.tex", "w").write("\n".join(L) + "\n")

# ------------------------------------------------------------- mask figure
# mask.py counts its steps from 0; the figure and the text count from 1, as
# Algorithm J does, so that the step shown on the left is the fifth.
st = mask["steps"]
SHOWN = 5
s5 = st[SHOWN - 1]
bars = [(t, l, a) for t, l, a in s5["top"]]
seen = {t for t, _, _ in bars}
bars += [(t, l, True) for t, l in s5["allowed"] if t not in seen]
bars.sort(key=lambda b: -b[1])
M = []
M.append("% Figure: constrained decoding with Qwen3-0.6B (MLX, 4-bit) and the")
M.append("% language {\"unit\": \"celsius\"|\"fahrenheit\"} with optional spaces.")
M.append("%% Left: logits at step %d; right: allowed tokens per step." % SHOWN)
M.append("% Generated by genfigs.py from mask.json.  Standalone: `make figures`.")
M.append(r"\begin{tikzpicture}[x=1cm, y=1cm,")
M.append(r"    lbl/.style={text height=3.6pt, text depth=1.2pt}]")
BX0, BW, LMAX = 1.45, 4.6, 26.0      # bar origin, bar width for LMAX
def xb(v): return BX0 + BW * v / LMAX
bh = 0.3
M.append(r"  \node[font=\sffamily\bfseries\scriptsize, text=ink, anchor=south west]"
         r" at (0,0.55) {Step %d: logits after \texttt{%s}};" % (SHOWN, tex(s5["prefix"])))
for v in range(0, 26, 5):
    M.append(r"  \draw[inkgrid, line width=0.3pt] (%.3f,0.3) -- (%.3f,%.2f);"
             % (xb(v), xb(v), -len(bars) * bh + 0.05))
    M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south] at (%.3f,0.3) {%d};"
             % (xb(v), v))
for i, (t, l, a) in enumerate(bars):
    y = -i * bh
    col = "cEngine" if a else "inkgrid"
    M.append(r"  \fill[%s, rounded corners=0.6pt] (%.3f,%.3f) rectangle (%.3f,%.3f);"
             % (col, xb(0), y - 0.09, xb(l), y + 0.09))
    tag = "" if a else r"\enspace{\color{muted}masked}"
    M.append(r"  \node[font=\ttfamily\tiny, text=%s, anchor=east, lbl] at (%.3f,%.2f) {%s};"
             % ("ink" if a else "muted", BX0 - 0.08, y, tex(t)))
    # white behind the value, so that no grid line runs through it
    M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=west, lbl, fill=white,"
             r" inner sep=1pt] at (%.3f,%.2f) {%.2f%s};"
             % (xb(l) + 0.04, y, l, tag))
# right panel: steps
RX = 7.65
M.append(r"  \node[font=\sffamily\bfseries\scriptsize, text=ink, anchor=south west]"
         r" at (%.2f,0.55) {Allowed tokens at each step (of %s)};"
         % (RX, "{:,}".format(mask["candidates"])))
PX = RX + 0.55                       # the output so far starts here
M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south west, lbl] at (%.2f,0.2)"
         r" {step};" % RX)
M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south west, lbl] at (%.2f,0.2)"
         r" {output so far};" % PX)
M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south, lbl] at (%.2f,0.2)"
         r" {allowed};" % (RX + 4.30))
M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=south west, lbl] at (%.2f,0.2)"
         r" {chosen};" % (RX + 5.20))
for i, s in enumerate(st):
    y = -i * 0.42
    M.append(r"  \node[font=\sffamily\tiny, text=ink2, anchor=east, lbl] at (%.2f,%.2f) {%d};"
             % (RX + 0.36, y, s["step"] + 1))
    M.append(r"  \node[font=\ttfamily\tiny, text=ink, anchor=west, lbl] at (%.2f,%.2f) {%s};"
             % (PX, y, tex(s["prefix"]) if s["prefix"] else r"{\color{muted}(empty)}"))
    M.append(r"  \fill[cEngine] (%.2f,%.3f) rectangle (%.3f,%.3f);"
             % (RX + 4.25, y - 0.08, RX + 4.25 + 0.12 * s["n_allowed"], y + 0.08))
    M.append(r"  \node[font=\sffamily\tiny, text=ink, anchor=east, lbl] at (%.2f,%.2f) {%d};"
             % (RX + 4.20, y, s["n_allowed"]))
    M.append(r"  \node[font=\ttfamily\tiny, text=ink, anchor=west, lbl] at (%.2f,%.2f) {%s};"
             % (RX + 5.20, y, tex(s["chosen"])))
M.append(r"\end{tikzpicture}")
open(f"{figdir}/ch09-mask.tex", "w").write("\n".join(M) + "\n")
print("ok", len(rows), "stream rows,", len(bars), "bars,", len(st), "steps")
