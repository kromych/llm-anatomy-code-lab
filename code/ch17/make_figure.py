# make_figure.py -- write figures/ch17-runs.tex from results/variance.csv
# and the per-question counts of the ten sampled runs (results/counts.csv).
# usage: python3 make_figure.py RESULTS FIGURE
import csv, math, statistics, sys

res, fig = sys.argv[1], sys.argv[2]
rows = list(csv.DictReader(open(f"{res}/variance.csv")))
counts = [int(r["correct"]) for r in csv.DictReader(open(f"{res}/counts.csv"))]
K = 10
means = [c / K for c in counts]
m = 100 * statistics.mean(means)
h = 100 * 1.96 * statistics.stdev(means) / math.sqrt(len(means))

groups = [("t0-serial", 1), ("t0-parallel", 2), ("t07-seed", 3)]
pts = []
for cond, x in groups:
    runs = [r for r in rows if r["condition"] == cond]
    runs.sort(key=lambda r: int(r["run"]))
    w = 0.06 if len(runs) > 3 else 0.12
    for j, r in enumerate(runs):
        xx = x + (j - (len(runs) - 1) / 2) * w
        y = 100 * float(r["accuracy"])
        lo, hi = 100 * float(r["lo"]), 100 * float(r["hi"])
        pts.append(f"      ({xx:.3f},{y:.1f}) += (0,{hi - y:.1f}) "
                   f"-= (0,{y - lo:.1f})")
coords = "\n".join(pts)

tex = rf"""% Figure: scores of repeated runs of one task (Gemma 3 1B, Q8_0, first
% 100 GSM8K problems, Inspect + llama-server with 8 slots), with 95 %
% Wilson intervals; band: mean of the ten sampled runs with its interval.
% Generated by code/ch17/make_figure.py from code/ch17/results; do not edit
% the coordinates by hand.
% Standalone: `make figures` -> build/figures/ch17-runs.pdf
\begin{{tikzpicture}}
  \begin{{axis}}[width=11.5cm, height=6.2cm, scale only axis=false,
      xmin=0.45, xmax=3.55, ymin=36, ymax=74,
      xtick={{1,2,3}},
      xticklabels={{{{temperature 0,\\serial}},{{temperature 0,\\8 parallel}},
        {{temperature 0.7,\\seeds 1--10}}}},
      xticklabel style={{align=center}},
      ylabel={{problems solved (of 100)}},
      label style={{font=\sffamily\scriptsize, text=ink2}},
      tick label style={{font=\sffamily\scriptsize, text=ink2}},
      axis line style={{inkaxis}}, major tick style={{inkaxis}},
      xtick style={{draw=none}}, ymajorgrids,
      major grid style={{inkgrid, line width=0.3pt}},
      error bars/error bar style={{ink2, line width=0.5pt}},
      error bars/error mark options={{rotate=90, mark size=1.5pt, ink2}}]
    \fill[inkgrid!70!white] (axis cs:2.62,{m - h:.1f})
      rectangle (axis cs:3.38,{m + h:.1f});
    \draw[ink2, line width=0.6pt] (axis cs:2.62,{m:.1f})
      -- (axis cs:3.38,{m:.1f});
    \node[font=\sffamily\scriptsize, text=ink2, anchor=south east,
      inner sep=1pt] at (axis cs:3.44,71.0)
      {{mean of the sampled runs: {m:.1f}}};
    \draw[link] (axis cs:3.34,70.7) -- (axis cs:3.34,{m + 0.4:.1f});
    \addplot[only marks, mark=*, mark size=1.8pt,
      mark options={{draw=series1, fill=series1}},
      error bars/.cd, y dir=both, y explicit]
      coordinates {{
{coords}}};
  \end{{axis}}
\end{{tikzpicture}}
"""
open(fig, "w").write(tex)
print(f"mean {m:.1f} +- {h:.1f}")

