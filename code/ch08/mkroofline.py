"""Rooflines of the devices in the chapter's table of peaks and bandwidths,
with the measured rates of the instruction-set study marked on them, as a
pgfplots figure.

Usage: python3 code/ch08/mkroofline.py lab/bench/isa/results.csv \
           figures/ch08-roofline.tex

The roofs are min(F, I B). F and B of four devices come from data sheets
(the table cites them); the GPU of S3-macOS (krom1u) has the F that the
serving chapter fitted from a prefill of Qwen3-8B, and Apple's bandwidth.
The measured points are llama-bench rates of Gemma 3 1B (999.89 M
parameters; file sizes as llama-bench prints them): the native CPU build
on S1-LinuxX64 (xps-8930) and the Metal backend on S3-macOS. A rate of r
tokens per second is r * 2N operations per second; the intensity counts
the bytes of the file once per token (tg128) or once per prompt of 512
tokens (pp512). The table printed on standard output compares each point
with its roof.
"""
import csv, sys

N = 999.89e6                         # parameters of Gemma 3 1B
MIB = {"Q4_0": 682.24, "Q8_0": 1013.54, "Q4_K_M": 762.49}
XMIN, XMAX, YMIN, YMAX = 0.25, 3000, 0.01, 4000

ROOFS = [  # label, F in TFLOP/s, B in TB/s, anchor and x of the label
    ("AMD MI300X", 1307.4, 5.3, "south east", XMAX),
    ("NVIDIA H100 SXM", 989, 3.35, "north east", XMAX),
    ("GeForce RTX 4090", 165.2, 1.008, "south east", XMAX),
    ("M1 Ultra GPU", 13.2, 0.8, "north", 165),   # clear of the marks
    ("Core i7-8700, FP32", 0.6144, 0.0416, "south east", XMAX),
]
LEGEND_X, LEGEND_Y = 5.5, 0.0546     # first mark of the legend
COLOR = {4: "series1", 3: "series2"}  # roofs of the lab, and their marks
MEASURED = [  # host, prefix of isa_variant, threads, roof, mark, legend
    ("xps-8930", "native (", "6", 4, "o", r"\SysLinuxX{}, measured"),
    ("krom1u", "Homebrew: Metal", "16", 3, "square",
     r"\SysMac{} GPU, measured"),
]

def points(rows, host, prefix, threads):
    for q, mib in MIB.items():
        m = [r for r in rows if r["host"] == host and r["threads"] == threads
             and r["isa_variant"].startswith(prefix) and r["repack"] == "1"
             and r["model_quant"] == q]
        assert len(m) == 1, (host, prefix, q, len(m))
        per_byte = 2 * N / (mib * 2**20)           # operations per byte
        for test, n in (("tg128", 1), ("pp512", 512)):
            rate = float(m[0][test + "_tps"])
            yield q, test, n * per_byte, rate * 2 * N / 1e12

def roof(F, B, x):
    return min(F, x * B)

rows = list(csv.DictReader(open(sys.argv[1])))
marks, legend = [], []
print("host      quant   test   op/byte   TFLOP/s    roof  fraction")
for k, (host, prefix, threads, i, mark, text) in enumerate(MEASURED):
    _, F, B, _, _ = ROOFS[i]
    pts = list(points(rows, host, prefix, threads))
    for q, test, x, y in pts:
        print(f"{host:9s} {q:7s} {test:6s} {x:7.1f} {y:9.4f} "
              f"{roof(F, B, x):7.3f} {y / roof(F, B, x):8.2f}")
    coords = " ".join(f"({x:.4g},{y:.4g})" for _, _, x, y in pts)
    style = (f"only marks, mark={mark}, mark size=1.7pt, "
             f"draw={COLOR[i]},\n"
             "             line width=0.5pt")
    marks.append(f"    \\addplot[{style}]\n      coordinates {{{coords}}};")
    yl = LEGEND_Y / 1.82**(k + 1)
    legend.append(f"    \\addplot[{style}]\n"
                  f"      coordinates {{({LEGEND_X},{yl:.4g})}};\n"
                  "    \\node[plate, font=\\sffamily\\tiny, text=ink2, "
                  "anchor=west]"
                  f" at (axis cs:{LEGEND_X * 1.2:.4g},{yl:.4g})\n"
                  f"      {{{text}}};")

if len(sys.argv) > 2:
    # the two devices of the lab take a color, which their marks share
    roofs = "\n".join(
        f"    \\addplot[roof{', ' + COLOR[i] if i in COLOR else ''}] "
        f"coordinates {{({XMIN},{XMIN * B:.4g}) "
        f"({F / B:.4g},{F:.4g}) ({XMAX},{F:.4g})}};"
        for i, (_, F, B, _, _) in enumerate(ROOFS))
    ridges = " ".join(f"({F / B:.4g},{F:.4g})" for _, F, B, _, _ in ROOFS)
    labels = "\n".join(
        f"      \\node[plate, anchor={a}, "
        f"yshift={'-' if a.startswith('north') else ''}1.2pt] "
        f"at (axis cs:{x},{F:.4g}) {{{name}}};"
        for name, F, B, a, x in ROOFS)
    open(sys.argv[2], "w").write(r"""% Figure: roofline of five devices, with the arithmetic intensity of four
% workloads of an 8B model (one 4096 x 4096 weight matrix, 16-bit
% activations).  Peaks are vendor figures for dense 16-bit matrix
% arithmetic; the CPU is the Core i7-8700 of the lab, FP32 at base clock;
% the M1 Ultra GPU has the rate fitted in the serving chapter (the check
% of the simulation against a real device).  Open marks:
% llama-bench rates of Gemma 3 1B from lab/bench/isa/results.csv.
% Generated by code/ch08/mkroofline.py; do not edit the coordinates by hand.
% Standalone: `make figures` -> build/figures/ch08-roofline.pdf
\begin{tikzpicture}[
    roof/.style={draw=ink2, line width=1.1pt, mark=none},
    work/.style={draw=muted, line width=0.6pt, dash pattern=on 2pt off 2pt},
  ]
  \begin{axis}[
      width=13.6cm, height=8.6cm,
      xmode=log, ymode=log,
      xmin=0.25, xmax=3000, ymin=0.01, ymax=4000,
      xtick={1,10,100,1000},
      xticklabels={1,10,100,1{,}000},
      ytick={0.01,0.1,1,10,100,1000},
      yticklabels={0.01,0.1,1,10,100,1{,}000},
      minor tick num=0,
      xlabel={arithmetic intensity (floating-point operations per byte, log scale)},
      ylabel={attainable TFLOP/s (log scale)},
      label style={font=\sffamily\scriptsize, text=ink2},
      tick label style={font=\sffamily\scriptsize, text=ink2},
      axis line style={inkaxis},
      major tick style={inkaxis},
      grid=major, major grid style={inkgrid, line width=0.3pt},
      clip=false,
    ]
    % workloads (thresholds read against the roofs)
    \foreach \x/\t in {1.0/{decode, 16-bit},
                       3.55/{decode, 4.5-bit},
                       62.1/{decode, batch 64},
                       409.6/{prefill, 512 tokens}} {
      \edef\temp{\noexpand\draw[work] (axis cs:\x,0.01) -- (axis cs:\x,4000);
        \noexpand\node[font=\noexpand\sffamily\noexpand\tiny, text=ink,
          anchor=south, align=center] at (axis cs:\x,4000) {\t};}
      \temp
    }
    % roofs: min(F, I B)
""" + roofs + r"""
    % ridge points
    \addplot[only marks, mark=*, mark size=1.8pt, draw=white, fill=ink,
             line width=0.5pt]
      coordinates {""" + ridges + r"""};
    % direct labels at the right end of each roof
    \begin{scope}[font=\sffamily\scriptsize, text=ink]
""" + labels + r"""
    \end{scope}
    % measured rates (the instruction-set study of this chapter)
""" + "\n".join(marks) + r"""
    % legend
    \addplot[only marks, mark=*, mark size=1.8pt, draw=white, fill=ink,
             line width=0.5pt]
      coordinates {(""" + f"{LEGEND_X},{LEGEND_Y}" + r""")};
    \node[plate, font=\sffamily\tiny, text=ink2, anchor=west] at (axis cs:"""
        + f"{LEGEND_X * 1.2:.4g},{LEGEND_Y}" + r""")
      {ridge point $F/B$};
""" + "\n".join(legend) + r"""
  \end{axis}
\end{tikzpicture}
""")
