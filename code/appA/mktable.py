r"""Generate the version table of Appendix A from versions.csv.

The table is taller than a page, so it is written as an xltabular, which
breaks across pages: the caption, the label and the repeated head are part
of the environment and therefore of this program. The rows of a group end
in \\*, which forbids a page break after them, so in the print edition
the table breaks between groups. On the taller page of the screen edition
that would leave a third of the page in front of the table empty, so there
a group may break as well, two rows or more from either of its ends: the
rows in between end in \grouprow, which is \\* in print and \\ on screen.

Usage: python3 code/appA/mktable.py code/appA/versions.csv \
           chapters/appA-versions.tex
"""
import csv, re, sys

# The lab systems of Table A.1, as macros of tex/preamble.tex; the CSV keeps
# the host names that the code supplement and lab/hosts use.
SYSTEMS = {"xps-8930": (1, r"\SysLinuxX{}"), "krom2": (2, r"\SysLinuxArm{}"),
           "krom1u": (3, r"\SysMac{}"), "kromyrzen": (4, r"\SysWin{}"),
           "kr0m-gpu": (5, r"\SysCloud{}")}

COLUMNS = r"  Tool & Version & Observed on \\"
HEAD = [
    "% Generated by code/appA/mktable.py from code/appA/versions.csv;",
    "% edit the CSV (rows) or the program (caption, head), not this file.",
    r"\begingroup",
    r"\footnotesize",
    r"\ifnum\bookprint=1 \def\grouprow{\\*}\else \def\grouprow{\\}\fi",
    r"\setlength\LTcapwidth{\linewidth}",
    r"\begin{xltabular}{\linewidth}{@{}l l L@{}}",
    r"  \caption[Pinned versions]{The versions with which the book was",
    r"    tested, and the systems of \cref{tab:appA-machines} on which we",
    r"    observed them (\enquote{all four} means \SysLinuxX{} to \SysWin{}).",
    r"    Generated from \path{code/appA/versions.csv}.}%",
    r"  \label{tab:appA-versions}\\",   # a space here would shift the caption
    r"  \toprule",
    COLUMNS,
    r"  \midrule",
    r"  \endfirsthead",
    r"  \multicolumn{3}{@{}l@{}}{\cref{tab:appA-versions}, continued} \\",
    r"  \addlinespace",
    r"  \toprule",
    COLUMNS,
    r"  \midrule",
    r"  \endhead",
    r"  \midrule",
    r"  \multicolumn{3}{@{}r@{}}{\itshape continued on the next page} \\",
    r"  \endfoot",
    r"  \bottomrule",
    r"  \endlastfoot",
]
TAIL = [r"\end{xltabular}", r"\endgroup", ""]

def systems(where):
    """'xps-8930; krom1u (venv)' -> S1 label; S3 label (venv), in S order.
    Four of the five systems, without remarks, become 'all but' the
    fifth, which keeps the cell on one line of the print page.
    Call on text that tex() has already escaped."""
    hosts = set(where.split("; "))
    if len(hosts) == 4 and hosts < set(SYSTEMS):
        (other,) = set(SYSTEMS) - hosts
        return "all but " + SYSTEMS[other][1]
    parts = []
    for p in where.split("; "):
        m = re.match(r"([A-Za-z0-9-]+)(.*)", p)
        if m and m.group(1) in SYSTEMS:
            order, macro = SYSTEMS[m.group(1)]
            parts.append((order, macro + m.group(2)))
        else:
            parts.append((0, p))
    return "; ".join(text for _, text in sorted(parts))

def tex(s):
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"),
                 ("%", r"\%"), ("#", r"\#"), ("~", r"\textasciitilde{}")):
        s = s.replace(a, b)
    return s

def refs(s):
    """A chapter is given in the CSV by its label, never by its number:
    'source read for ch:frameworks' -> '... \\cref{ch:frameworks}'."""
    return re.sub(r"\b((?:ch|app|sec|tab):[A-Za-z0-9-]+)", r"\\cref{\1}", s)

rows = list(csv.DictReader(open(sys.argv[1], newline="")))
out = list(HEAD)
for i, r in enumerate(rows):
    if i == 0 or r["group"] != rows[i - 1]["group"]:
        if i:
            out.append(r"  \addlinespace")
        title = rf"\itshape {tex(r['group'])}"
        out.append(rf"  \multicolumn{{3}}{{@{{}}l}}{{{title}}} \\*")
    group = [j for j, q in enumerate(rows) if q["group"] == r["group"]]
    k, n = i - group[0], len(group)       # row k of the n in its group
    end = (r"\\" if k == n - 1 else
           r"\\*" if k in (0, n - 2) else r"\grouprow")
    out.append(rf"  {tex(r['tool'])} & {tex(r['pinned'])} & "
               rf"{refs(systems(tex(r['where'])))} " + end)
open(sys.argv[2], "w").write("\n".join(out + TAIL))
