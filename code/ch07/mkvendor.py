"""mkvendor.py OUT.tex -- write figures/ch07-vendor.tex (fig:ch7-vendor):
the output speed of one request on the lab's machines, at hosted endpoints,
and in vendors' own figures.

Usage: python3 code/ch07/mkvendor.py figures/ch07-vendor.tex

The lab values are the best tg128 rates of lab/bench/isa/results.csv for
each machine; the others are rows of lab/reference/vendor-speeds.md, whose
IDs stand in the comments. Both rows of GPT-6.1 Sol are at maximum effort,
so that they differ in the service tier alone: I11 gives 221.1 for the
Ultrafast tier and, in its conditions, 43.5 for the standard tier.
"""
import sys

G = [
    ("Measured here: Gemma 3 1B", "lab", [
        (r"\SysLinuxX, CPU", 42.96), (r"\SysWin, CPU", 36.52),
        (r"\SysLinuxArm, CPU", 59.25), (r"\SysMac, CPU", 162.53),
        (r"\SysMac, GPU", 186.33)]),
    ("Open models, hosted", "aa", [
        ("Llama 3.1 8B, CoreWeave", 148.5),             # I6
        ("Llama 3.1 8B, Groq", 631.3),                  # I5
        ("Llama 3.3 70B, Groq", 321.7),                 # I7
        ("gpt-oss-120B, Amazon Bedrock", 115.0),        # I4
        ("gpt-oss-120B, Groq", 459.6),                  # I3
        ("gpt-oss-120B, SambaNova", 643.9),             # I2
        ("gpt-oss-120B, Cerebras", 1849.2)]),           # I1
    ("Models on their makers' APIs", "aa", [
        ("GPT-6.1 Sol, standard tier", 43.5),           # I11, conditions
        ("Grok 4.7", 61.2),                             # I13
        ("DeepSeek V4 Pro", 83.6),                      # I14
        ("Claude Opus 5.5", 109.8),                     # I8
        ("Mistral Large 4", 110.3),                     # I15
        ("Claude Haiku 5.5", 215.4),                    # I9
        ("Gemini 4 Hydrogen", 216.5),                   # I12
        ("GPT-6.1 Sol, Ultrafast tier", 221.1)]),       # I11
    ("Vendors' claims", "claim", [
        ("DeepSeek-V3, DeepSeek API", 60, "="),         # P9
        ("DeepSeek-V4-Pro, GB200 NVL72", 150, ">"),     # H9
        ("DeepSeek-R1, SambaNova SN40L", 198, "="),     # H17
        ("DeepSeek-R1, DGX B200", 250, ">"),            # H1
        ("Kimi K3, TPU Ironwood", 700, ">"),            # H19
        ("Llama 4 Maverick, DGX B200", 1000, ">"),      # H3
        ("Gemini Diffusion", 1479, "="),                # P5
        ("Llama 4 Maverick, Cerebras", 2522, "="),      # H11
        ("Gemma 4 31B, Groq 3 LPX", 3431, "=")]),       # H10
]

rows, heads, pts = [], [], {"lab": [], "aa": [], "eq": [], "gt": []}
y = 0
for title, kind, items in G:
    y += 1
    heads.append((y, title))
    for it in items:
        y += 1
        rows.append((y, it[0]))
        k = kind if kind != "claim" else ("gt" if it[2] == ">" else "eq")
        pts[k].append((it[1], y))
N = y

HEAD = r"""% Figure: output speed of one request, in tokens per second on
% a log scale: the generation rates measured for this book (Gemma 3 1B,
% llama-bench tg128, sec:ch8-isa and lab/bench/isa/results.csv), hosted
% endpoints as measured by Artificial Analysis (1k-token workload, five-day
% average read on 2026-11-14; both rows of GPT-6.1 Sol at maximum effort),
% and figures published by vendors.  Sources for every row:
% lab/reference/vendor-speeds.md.  Generated by code/ch07/mkvendor.py.
% Standalone: `make figures` -> build/figures/ch07-vendor.pdf
\begin{tikzpicture}
  \begin{axis}[xmode=log, xmin=20, xmax=5000,
      xtick={20,50,100,200,500,1000,2000,5000},
      xticklabels={20,50,100,200,500,{1,000},{2,000},{5,000}},
      y dir=reverse, ymin=0.45, ymax=@YMAX@, scale only axis,
      width=8.4cm, height=@HEIGHT@cm,
      label style={font=\sffamily\scriptsize, text=ink2},
      tick label style={font=\sffamily\scriptsize, text=ink2},
      axis line style={inkaxis}, major tick style={inkaxis}, xmajorgrids,
      major grid style={inkgrid, line width=0.3pt}, ytick style={draw=none},
      clip mode=individual,
      ytick={@YTICKS@},
      yticklabels={@YLABELS@},
      xlabel={output tokens per second for one request (log scale)},
      legend style={draw=none, fill=none, font=\sffamily\scriptsize,
        text=ink, at={(0.5,1.02)}, anchor=south, legend columns=2,
        /tikz/every even column/.append style={column sep=10pt}},
      legend cell align=left]"""

fill = {"@YMAX@": f"{N}.55", "@HEIGHT@": f"{0.29 * N:.2f}",
        "@YTICKS@": ",".join(str(r[0]) for r in rows),
        "@YLABELS@": ",%\n        ".join("{" + r[1] + "}" for r in rows)}
for k, v in fill.items():
    HEAD = HEAD.replace(k, v)
out = [HEAD]
for y, _ in heads[1:]:
    out.append(f"    \\draw[inkaxis, line width=0.4pt] "
               f"(axis cs:20,{y - 0.5}) -- (axis cs:5000,{y - 0.5});")
for y, t in heads:
    out.append("    \\node[anchor=west, inner xsep=0pt, "
               "font=\\sffamily\\scriptsize\\bfseries, text=ink]\n"
               f"      at ([xshift=-4.35cm]axis cs:20,{y}) {{{t}}};")
style = {   # mark, draw, fill, size, legend entry
    "lab": ("*", "series1", "series1", "2.0pt", "measured here"),
    "aa": ("square*", "series2", "series2", "1.8pt",
           "measured by Artificial Analysis"),
    "eq": ("diamond*", "series3", "white", "2.3pt", "vendor's figure"),
    "gt": ("triangle*", "series3", "white", "2.3pt",
           "vendor's figure, ``more than''")}
for k in ("lab", "aa", "eq", "gt"):
    m, d, f, sz, name = style[k]
    rot = ", rotate=-90" if k == "gt" else ""
    coords = " ".join(f"({v},{y})" for v, y in pts[k])
    out.append(f"    \\addplot[only marks, mark={m}, mark size={sz},\n"
               f"      mark options={{draw={d}, fill={f}, "
               f"line width=0.5pt{rot}}}]\n"
               f"      coordinates {{{coords}}};")
    out.append(f"    \\addlegendentry{{{name}}}")
out.append("  \\end{axis}\n\\end{tikzpicture}\n")
open(sys.argv[1], "w").write("\n".join(out))
