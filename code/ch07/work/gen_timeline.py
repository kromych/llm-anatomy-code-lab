# gen_timeline.py OUT.tex -- write figures/ch07-timeline.tex: eight
# requests under static and continuous batching (fig:ch7-timeline), with
# all times taken from sim.py. Usage, from the root of the book:
#   python3 code/ch07/work/gen_timeline.py figures/ch07-timeline.tex
import copy, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sim

spec = [(0.00, 1800, 40), (0.02, 400, 120), (0.05, 900, 25),
        (0.08, 300, 90), (0.15, 1200, 60), (0.20, 600, 30),
        (0.30, 1500, 100), (0.35, 500, 45)]     # arrival, prompt, output
reqs = [dict(id=i, arr=a, p=p, o=o) for i, (a, p, o) in enumerate(spec)]
S = sim.static(copy.deepcopy(reqs), 4)
C = sim.continuous(copy.deepcopy(reqs))
X0, XS, ROW, BH = 2.6, 4.7, 0.36, 0.22
TINY = "font=\\sffamily\\tiny"

def X(t):
    return X0 + XS * t

L = []
w = L.append
w("% Figure: static versus continuous batching of the same eight requests.")
w("% Generated by code/ch07/work/gen_timeline.py from the simulator of")
w("% the section sec:ch7-sim (sim.py); all times come from the simulation.")
w("% Standalone: `make figures` -> build/figures/ch07-timeline.pdf")
w("\\begin{tikzpicture}[x=1cm, y=1cm]")

def bar(shade, x0, x1, y):
    w(f"  \\fill[cEngine!{shade}] ({x0:.3f},{y - BH / 2:.3f}) rectangle "
      f"({x1:.3f},{y + BH / 2:.3f});")

def panel(rs, y0, title, held):
    w("  \\node[anchor=south west, font=\\sffamily\\bfseries\\scriptsize, "
      f"text=ink] at (0,{y0 + 0.42:.3f}) {{{title}}};")
    w(f"  \\node[anchor=south west, {TINY}, text=ink2] "
      f"at (0,{y0 + 0.16:.3f}) {{request: prompt / output tokens}};")
    ybot = y0 - 8 * ROW + ROW / 2 - 0.05
    for k in range(5):
        x = X(0.5 * k)
        w(f"  \\draw[inkgrid, line width=0.3pt] ({x:.3f},{y0 + 0.2:.3f}) "
          f"-- ({x:.3f},{ybot:.3f});")
    for r in rs:
        y = y0 - r["id"] * ROW
        xa, xs = X(r["arr"]), X(r["start"])
        w(f"  \\node[anchor=east, {TINY}, text=ink2] "
          f"at ({X0 - 0.12:.3f},{y:.3f}) "
          f"{{{r['id'] + 1}:\\enspace {r['p']:,} / {r['o']}}};")
        w(f"  \\draw[ink2, line width=0.5pt] ({xa:.3f},{y:.3f}) "
          f"-- ({xs:.3f},{y:.3f});")
        w(f"  \\draw[ink2, line width=0.5pt] ({xa:.3f},{y - 0.07:.3f}) "
          f"-- ({xa:.3f},{y + 0.07:.3f});")
        if held and r["free"] > r["end"] + 1e-6:
            bar("12!white", X(r["end"]), X(r["free"]), y)
        pe = max(X(r["first"]), xs + 0.05)
        bar("45!white", pe, X(r["end"]), y)
        bar("85!black", xs, pe, y)
    for k in range(5):
        t = 0.5 * k
        w(f"  \\node[{TINY}, text=ink2, anchor=north] "
          f"at ({X(t):.3f},{ybot:.3f}) {{{t:.1f}\\,s}};")
    end = max(r["free"] for r in rs)
    w(f"  \\draw[ink, line width=0.6pt] ({X(end):.3f},{y0 + 0.2:.3f}) "
      f"-- ({X(end):.3f},{ybot:.3f});")
    w(f"  \\node[{TINY}, text=ink, anchor=south east] "
      f"at ({X(end) - 0.05:.3f},{y0 + 0.16:.3f}) "
      f"{{all done at {end:.2f}\\,s}};")

panel(S, 0.0, "Static batching, batches of at most four", True)
panel(C, -4.25, "Continuous batching (Algorithm L)", False)
w(f"  \\begin{{scope}}[shift={{(0,-7.95)}}, {TINY}, text=ink]")
w("    \\draw[ink2, line width=0.5pt] (0.0,0) -- (0.5,0);")
w("    \\draw[ink2, line width=0.5pt] (0,-0.07) -- (0,0.07);")
w("    \\node[anchor=west] at (0.6,0) {waiting, from arrival};")
w("    \\fill[cEngine!85!black] (3.0,-0.11) rectangle (3.5,0.11);")
w("    \\node[anchor=west] at (3.6,0) {prefill};")
w("    \\fill[cEngine!45!white] (4.7,-0.11) rectangle (5.2,0.11);")
w("    \\node[anchor=west] at (5.3,0) {decoding};")
w("    \\fill[cEngine!12!white] (6.7,-0.11) rectangle (7.2,0.11);")
w("    \\node[anchor=west] at (7.3,0) "
  "{finished, slot still held by the batch};")
w("  \\end{scope}")
w("\\end{tikzpicture}")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
